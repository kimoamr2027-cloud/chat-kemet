// أسامي فرعونية للزوار (الشات بيختار واحد على حسب النوع + رقم صغير علشان مايتكررش)
const MALE = ['رمسيس', 'أحمس', 'خوفو', 'خفرع', 'منقرع', 'مينا', 'سيتي', 'تحتمس', 'أمنحتب', 'زوسر', 'حورس', 'أوزوريس', 'بتاح', 'أخناتون', 'توت', 'سنفرو', 'إمحوتب', 'آمون', 'رع', 'أنوبيس', 'تحوت', 'بسماتيك', 'شيشنق', 'مرنبتاح', 'كاموس']
const FEMALE = ['نفرتيتي', 'حتشبسوت', 'كليوباترا', 'نفرتاري', 'إيزيس', 'حتحور', 'تي', 'ماعت', 'باستيت', 'نيت', 'ميريت', 'سخمت', 'نفتيس', 'أحمس نفرتاري', 'تاوسرت', 'عنخ إسن آمون', 'حنوت', 'نوت', 'سشات', 'مريت آمون']
const AR = '٠١٢٣٤٥٦٧٨٩'
const ar = (n) => String(n).replace(/\d/g, (d) => AR[d])
export function pharaohName(gender) {
  const list = gender === 'female' ? FEMALE : MALE
  return `${list[Math.floor(Math.random() * list.length)]} ${ar(10 + Math.floor(Math.random() * 990))}`
}
